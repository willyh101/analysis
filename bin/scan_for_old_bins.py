"""
Utility for scanning for old *.bin files and generated by suite2p and delete them.
"""

from pathlib import Path
import shutil
import time

DRY_RUN = False
MODE = 'delete' # 'delete' or 'move'

# Define the path to the parent directory containing the old binaries
# search_dir = '/mnt/nvme/data/suite2p_outputs'
# search_dir = '/mnt/nvme/localdata'
search_dir = '/mnt/nvme/scratch'

# How many days old should the binaries be to be considered old?
days_old = 10

# set the current time
current_time = time.time()


# some utilities
def file_info(file_path: Path) -> tuple[int, int]:
    last_access_date = file_path.stat().st_atime
    age_in_days = (current_time - last_access_date) / (60 * 60 * 24)
    file_size = file_path.stat().st_size
    return int(age_in_days), file_size

def find_mount_point(path) -> Path:
    path = Path(path).resolve()  # Resolve any symlinks
    while not path.is_mount():
        path = path.parent
    return path


# begin the main script
search_dir = Path(search_dir)
drive_path = find_mount_point(search_dir)
files_to_delete = []
total_size = 0
delete_size = 0
for path in Path(search_dir).rglob('*.bin'):
    file_age, file_size = file_info(path)
    total_size += file_size 
    if file_age > days_old:
        files_to_delete.append((path, file_age))
        delete_size += file_size

files_to_delete.sort(key=lambda x: x[1], reverse=True)

total, used, free = shutil.disk_usage(drive_path)

print(f"Found {len(files_to_delete)} files to delete (older than {days_old} days old).")
print(f'Files marked for deletion:')
for file_path, days_ago in files_to_delete:
    fpath = file_path.relative_to(Path(search_dir).parent)
    print(f'{fpath} - {days_ago} days ago')
total_size_gb = total_size / (1024 ** 3)
delete_size_gb = delete_size / (1024 ** 3)
print(f'\nTotal spaced taken up by *.bin files: {total_size_gb:.2f} GB')
print(f'Total space to be freed (>{days_old} days old): {delete_size_gb:.2f} GB')
print(f'Total space on drive: {total / (1024 ** 3):.2f} GB')
print(f'Total space free on drive: {free / (1024 ** 3):.2f} GB')

if not DRY_RUN:
    result = input('Delete files? (y/N): ').lower()
    if result == 'y':
        for file_path, _ in files_to_delete:
            if MODE == 'delete':
                file_path.unlink()
            # elif MODE == 'move':
            #     file_path.rename(file_path.with_suffix('.old'))
        print('Files deleted.')
    else:
        print('Exiting... No File deleted or moved.')